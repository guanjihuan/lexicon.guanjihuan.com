#!/usr/bin/env python3
"""Generate js/data.js from the curated word list.

Inputs : data/words.json  (curated word list, produced by tools/curate.py)
         data/cats.json   (curated classified subset)
Output : js/data.js       (window.WL_WORDS / window.WL_CATS)

Run from the project root:  python3 tools/make_data.py
"""
import json, os, sys

# 严格 JSON 读取：重复键必须报错（标准库会静默覆盖，人写的 JSON 易踩）
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from _strict_json import load_json  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
words = load_json(os.path.join(ROOT, 'data', 'words.json'))
cats = load_json(os.path.join(ROOT, 'data', 'cats.json'))

# keep the payload small: only the fields the front-end actually uses
clean = []
for w in words:
    e = {'num': w['num'], 'word': w['word'], 'senses': w['senses'], 'links': w['links']}
    if w.get('notes'):
        e['notes'] = w['notes']
    if w.get('pos'):
        e['pos'] = w['pos']
    if w.get('sub'):
        e['sub'] = w['sub']
    if w.get('reg'):
        e['reg'] = w['reg']
    if w.get('catGloss'):
        e['catGloss'] = w['catGloss']
    if w.get('core'):
        e['core'] = True
    clean.append(e)

payload = json.dumps(clean, ensure_ascii=False, separators=(',', ':'))
cats_payload = json.dumps(cats, ensure_ascii=False, separators=(',', ':'))
# v36-①(册四十九): 头行不再刻生成日期——跨日重跑曾致 ZERO_DRIFT 假漂移
out = ("// Auto-generated by tools/make_data.py — do not edit by hand.\n"
       "// Curated from https://www.guanjihuan.com/archives/4418 (800-word list, CC BY)\n"
       "//              https://www.guanjihuan.com/archives/24732 (344-word classified selection)\n"
       "// Manual edits live in data/curation.json and are applied by tools/curate.py.\n"
       "window.WL_WORDS = %s;\n"
       "window.WL_CATS = %s;\n" % (payload, cats_payload))
dst = os.path.join(ROOT, 'js', 'data.js')
os.makedirs(os.path.dirname(dst), exist_ok=True)


def dump_atomic(path, text):
    """原子写(v36-④ 册四十九同规): tmp+os.replace,写一半崩溃不再留半截产物"""
    tmp = path + '.tmp'
    with open(tmp, 'w', encoding='utf-8') as f:
        f.write(text)
    os.replace(tmp, path)


dump_atomic(dst, out)
print("wrote %s (%d bytes), %d words, %d categorized" % (dst, len(out.encode('utf-8')), len(words), len(cats)))
