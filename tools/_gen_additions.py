require_curation_segments(cur, ('remove', 'fix', 'recat', 'add'))
raw = load_json(os.path.join(ROOT, 'data', 'words800.json'))
cats = load_json(os.path.join(ROOT, 'data', 'categorized.json'))
existing = {w['word'] for w in raw} | {c['word'] for c in cats}
removed = set(cur['remove'])
fixed_new = {v.get('word', k) for k, v in cur['fix'].items()}
clash = (existing - removed) | fixed_new
bad = [a['word'] for a in adds if a['word'] in clash]
if bad:
    raise SystemExit("additions clash with existing entries: %s" % bad)
bad2 = [r for r in cur['remove'] if r not in existing]
if bad2:
    raise SystemExit("remove list contains unknown words: %s" % bad2)
for k in cur['fix']:
    if k not in existing:
        raise SystemExit("fix key not found: %r" % k)
# recat 的键可能是改名后的词形（如 attribute sth to sb -> attribute to）
renamed = {v.get('word', k) for k, v in cur['fix'].items()}
known_recat = (existing - removed) | renamed | {a['word'] for a in cur['add']}
for k in cur['recat']:
    if k not in known_recat:
        raise SystemExit("recat key not found: %r" % k)

cur['add'] = adds
with open(cur_path + '.tmp', 'w', encoding='utf-8') as f:   # v36-④(册四十九): tmp+os.replace 原子写
    json.dump(cur, f, ensure_ascii=False, indent=1)   # 与仓库既有格式一致（四十六轮:原 indent=2 令每次重跑整文件重排缩进）
    f.write('\n')
os.replace(cur_path + '.tmp', cur_path)
print("additions: %d" % len(adds))
by = collections.Counter(a['pos'] for a in adds)
for k, v in by.items():
    print("  %s: %d" % (k, v))
