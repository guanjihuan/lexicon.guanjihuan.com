#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Generate js/examples.js from the curated example sentences.

Input : data/examples.json   {word: [{en, zh}, ...]}  (produced by tools/merge_examples.py)
Output: js/examples.js       (window.WL_EXAMPLES)

Kept in a separate file from js/data.js so the word table stays lean and so
examples can be regenerated independently of data/curation.json.

Run from the project root:  python3 tools/make_examples.py
"""
import json, os, sys

# 严格 JSON 读取：重复键必须报错（标准库会静默覆盖，人写的 JSON 易踩）
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from _strict_json import load_json  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = os.path.join(ROOT, 'data', 'examples.json')
ex = load_json(src)

clean = {}
for word, pairs in ex.items():
    items = []
    for p in pairs:
        en = ' '.join(str(p['en']).split())
        zh = ' '.join(str(p['zh']).split())
        if en and zh:
            items.append({'en': en, 'zh': zh})
    if items:
        clean[word] = items

payload = json.dumps(clean, ensure_ascii=False, separators=(',', ':'))
# v36-①(册四十九): 头行不再刻生成日期——跨日重跑曾致 ZERO_DRIFT 假漂移
out = ("// Auto-generated by tools/make_examples.py — do not edit by hand.\n"
       "// Example sentences for each headword, keyed by the headword string.\n"
       "// Source: data/examples.json (built from data/examples_parts/*.json by tools/merge_examples.py).\n"
       "window.WL_EXAMPLES = %s;\n" % (payload,))
dst = os.path.join(ROOT, 'js', 'examples.js')
os.makedirs(os.path.dirname(dst), exist_ok=True)


def dump_atomic(path, text):
    """原子写(v36-④ 册四十九同规): tmp+os.replace,写一半崩溃不再留半截产物"""
    tmp = path + '.tmp'
    with open(tmp, 'w', encoding='utf-8') as f:
        f.write(text)
    os.replace(tmp, path)


dump_atomic(dst, out)
print("wrote %s (%d bytes), %d words, %d sentences"
      % (dst, len(out.encode('utf-8')), len(clean), sum(len(v) for v in clean.values())))
